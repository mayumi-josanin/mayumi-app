// お客様へのお知らせを掲載する道具。
//
// 文面の下書きは docs/お客様へのお知らせ.md にある。
// ここでは、その文面を「ブログ・お知らせ」に載せるだけ。
//
// 既存の handleAddBlog を通すので、公開設定・お知らせ一覧・更新日時などが
// 手で書くときと同じように揃う。シートに直接書き足さないこと。

// エディタは「ファイルの先頭の関数」を最初に選ぶ。
// 既定は下見にしておく。載せるときだけ、ここを お知らせを載せる() に書き換える。
// （2026-08-15「アプリの入り方が新しくなりました」掲載済み）
function いま実行する() {
  お知らせの下見();
}

var お知らせ_タイトル = 'アプリの入り方が新しくなりました';

var お知らせ_本文 = [
  'いつもご利用いただきありがとうございます。',
  '',
  'このたび、アプリの入り方をひとつにまとめました。',
  'これまでアプリごとにお名前やパスコードを入れていただいていましたが、',
  'これからは最初の画面で一度だけで済むようになります。',
  '',
  '■ 一度だけ、ログインをお願いします',
  'これまでと同じお名前とパスコードでお入りいただけます。',
  '一度お入りいただければ、そのあとは90日間そのままお使いいただけます。',
  'スタンプなどのこれまでの記録は、そのまま残っています。',
  '',
  '■ 変わること',
  '・最初の画面でログインすると、ご利用いただけるアプリが並びます',
  '・アプリを切り替えるときに、もう聞かれません',
  '',
  '■ パスコードをお決めでない方',
  '最初の画面の「お困りのとき」→「パスコードを忘れた方」からご設定ください。',
  'お名前と、電話番号または生年月日のどちらかで確認できます。',
  '',
  '■ お願い',
  'アプリに入れないときも、新しく登録し直さないでください。',
  'これまでの記録が分かれてしまいます。',
  '「お困りのとき」からお進みいただくか、受付でお声がけください。',
  '',
  'ご不明な点は、受付でお気軽にお声がけください。',
].join('\n');

function お知らせ_中身_() {
  return {
    title: お知らせ_タイトル,
    body: お知らせ_本文,
    category: 'お知らせ',
    icon: '📢',
    status: '公開',
    noticeStatus: '公開',
  };
}

function お知らせの下見() {
  var d = お知らせ_中身_();
  Logger.log('■ これから載せる内容（まだ載せていません）');
  Logger.log('');
  Logger.log('タイトル: ' + d.title);
  Logger.log('カテゴリ: ' + d.category + ' / アイコン: ' + d.icon);
  Logger.log('公開設定: ' + d.status + ' / お知らせ一覧: ' + d.noticeStatus);
  Logger.log('');
  Logger.log('本文:');
  Logger.log(d.body);
  Logger.log('');
  Logger.log('文字数: ' + d.body.length);
  Logger.log('');
  Logger.log('これでよければ「お知らせを載せる」を実行してください。');
}

function お知らせを載せる() {
  var d = お知らせ_中身_();

  // 同じタイトルがすでにあれば、二重に載せない。
  var sheet = getOrCreateSpreadsheet().getSheetByName(SHEETS.BLOG);
  var 行数 = sheet.getLastRow();
  if (行数 > 1) {
    var titles = sheet.getRange(2, 2, 行数 - 1, 1).getValues();
    for (var i = 0; i < titles.length; i += 1) {
      if (String(titles[i][0] || '').trim() === d.title) {
        Logger.log('すでに同じタイトルのお知らせがあります（' + (i + 2) + '行目）。載せませんでした。');
        return;
      }
    }
  }

  var result = handleAddBlog(d);
  Logger.log('■ 載せました');
  Logger.log(JSON.stringify(result));
  Logger.log('');
  Logger.log('タイトル: ' + d.title);
  Logger.log('お客様のアプリの「NEWS」と「お知らせ一覧」に出ます。');
  Logger.log('取り消したいときは、管理アプリのお知らせ管理から削除してください。');
}
