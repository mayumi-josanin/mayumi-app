// お客様がいまアプリに入れる状態かどうかを、会員データから判定する道具。
//
//   入れるか確かめる()   … 全員を見て、入れない方を挙げる
//
// **読むだけ。**元のスプレッドシートは一切変えない。
//
// なぜ要るのか:
//   復元とパスコード再設定は、照合の条件が違う（2026-08-18 に調べた）。
//
//     復元          … **生年月日が必須一致。**登録が空だと絶対に通らない
//     パスコード再設定 … 登録にある項目だけ照合。電話か生年月日のどちらかが要る
//
//   つまり**生年月日が空の方は「復元」で永久に入れない。**
//   受付で登録して差し上げれば解決するが、まず誰がその状態かを知る必要がある。
//
//   サーバーの写しでも同じことは調べられるが、写しは古くなる。
//   **いまのシートを直接見るほうが確か。**

function 入れるか確かめる() {
  var ss = getOrCreateSpreadsheet();
  var sh = ss.getSheetByName(SHEETS.USERS);
  if (!sh) { Logger.log('会員データのシートがありません'); return; }

  var 最終行 = sh.getLastRow();
  var v = sh.getRange(1, 1, 最終行, sh.getLastColumn()).getValues();
  var 見出し = v[0].map(function (h) { return String(h).trim(); });

  function 列(名) { return 見出し.indexOf(名); }
  var c = {
    id: 列('ID'), 名: 列('氏名'), かな: 列('フリガナ'),
    電話: 列('電話番号'), 誕生日: 列('生年月日'),
    スタンプ: 列('現在スタンプ数'), 端末: 列('端末セッションJSON'),
    削除: 列('削除状態')
  };
  // 端末の列名はシートによって違うことがあるので、見つからなければ探す。
  if (c.端末 < 0) {
    for (var j = 0; j < 見出し.length; j += 1) {
      if (見出し[j].indexOf('端末') >= 0 || 見出し[j].indexOf('セッション') >= 0) { c.端末 = j; break; }
    }
  }

  var 文 = function (x) { return String(x === null || x === undefined ? '' : x).trim(); };

  var 入れない = [], 復元だけ不可 = [], 予備軍 = [], 全 = 0;

  for (var r = 1; r < v.length; r += 1) {
    var row = v[r];
    var id = 文(row[c.id]);
    if (!id) continue;
    if (c.削除 >= 0 && 文(row[c.削除])) continue;   // 退会は除く
    全 += 1;

    var 名 = 文(row[c.名]);
    var 電話 = 文(row[c.電話]);
    var 誕 = c.誕生日 >= 0 ? 文(row[c.誕生日]) : '';
    var 端末数 = 0;
    if (c.端末 >= 0) {
      var s = 文(row[c.端末]);
      if (s && s !== '[]') {
        try { var a = JSON.parse(s); 端末数 = (a && a.length) || 0; } catch (e) { 端末数 = 1; }
      }
    }
    var スタンプ = c.スタンプ >= 0 ? (Number(row[c.スタンプ]) || 0) : 0;

    var 記 = {
      行: r + 1, id: id, 名: 名, 電話: !!電話, 誕: !!誕,
      端末: 端末数, スタンプ: スタンプ
    };

    if (!誕 && !電話) {
      // どちらの入り口も通らない
      (端末数 === 0 ? 入れない : 予備軍).push(記);
    } else if (!誕) {
      // 復元は通らないが、パスコード再設定なら通る
      復元だけ不可.push(記);
    }
  }

  function 出す(題, 一覧, 説明) {
    Logger.log('■ ' + 題 + '（' + 一覧.length + '名）');
    if (説明) Logger.log('  ' + 説明);
    if (!一覧.length) { Logger.log('  該当なし'); Logger.log(''); return; }
    一覧.sort(function (a, b) { return b.スタンプ - a.スタンプ; });
    一覧.forEach(function (x) {
      Logger.log('    ' + x.行 + '行  ' + x.id + '  ' + x.名 +
        '  端末' + x.端末 + '台  スタンプ' + x.スタンプ);
    });
    Logger.log('');
  }

  Logger.log('■ 会員 ' + 全 + '名を確認しました（退会を除く）');
  Logger.log('');
  出す('いま入れません', 入れない,
    '電話番号も生年月日も無く、端末にも入っていない。**受付で登録するまで何をしても入れません。**');
  出す('「復元」では入れません', 復元だけ不可,
    '生年月日が無いので復元は通らない。**「パスコードの再設定」なら電話番号で入れます。**');
  出す('いまは入れているが、端末を失うと入れなくなります', 予備軍,
    '電話番号も生年月日も無い。機種変更や再インストールで入れなくなります。');

  Logger.log('  ※ 読むだけです。シートは変えていません。');
  Logger.log('  ※ 受付で**生年月日**を登録すれば、いずれも解決します。');
}
