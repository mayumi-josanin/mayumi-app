// 控え（データベースのバックアップ）が、ちゃんと届き続けているかを見張る道具。
//
//   控えが届いているか見る()   … いまの様子を1回だけ見る。**何も送りません**
//   控えの見張りを始める()     … 毎朝1回の見張りを仕掛ける
//   控えの見張りを止める()     … 見張りを外す
//
// ─────────────────────────────────────────────────────────
// なぜ要るのか
//
// 控えは自宅PCの予定表（mayumi-db-backup）が毎日3:00に取っている。
// **失敗しても誰も気づけない。**PCの電源が入っていない、Docker が落ちて
// いる、予定表が無効になった、どれも静かに起きる。
// 必要になるのは「壊れたとき」で、そのとき初めて「取れていなかった」と
// 分かるのでは遅い。
//
// **見張る側は、受け取る側（GAS）に置く。**
// 送る側（PC）に置くと、PCが止まったときに見張りごと止まる。
// 死んだ者に「死にました」とは言えない。
//
// ─────────────────────────────────────────────────────────
// 決めごと
//
// ・状態が変わったときだけ送る。毎日届いたら誰も読まなくなり、
//   本当に困ったときの1通が埋もれる（サーバーの見張りと同じ考え方）。
// ・フォルダは**IDで開く。名前で探さない。**
//   名前で探して同じ名前のフォルダが2つでき、「送れているのに0件」に
//   見えた前例がある（2026-08-17）。
// ・**控え受取_フォルダを用意する_() を呼ばない。**
//   あれは見つからなければ**新しいフォルダを作る。**見張りが本番とは別の
//   空フォルダを作り、それを見て「0件です」と鳴り続けることになる。

// 何時間 届かなかったら知らせるか。
// 3:00に取るので、丸一日空くと24時間。少し余裕を持たせて30時間。
// 短くすると、PCの再起動が長引いただけで鳴る。
var 控え見張り_猶予時間 = 30;

// これより小さい控えは、取れていないのと同じとみなす。
// 本番はいま 400KB ほど。10KB を切るのは明らかに異常。
var 控え見張り_小さすぎる = 10 * 1024;

var 控え見張り_状態の鍵 = 'BACKUP_WATCH_STATE';
var 控え見張り_扱う関数名 = '控えを見張る';

/**
 * ドライブの控えを新しい順に集める。**読むだけ。**
 *
 * フォルダIDが無い／開けないときは作らずに理由を返す。
 * 作ってしまうと、本番とは別の空フォルダを見続けることになる。
 */
function 控え見張り_集める_() {
  var id = PropertiesService.getScriptProperties().getProperty('BACKUP_FOLDER_ID');
  if (!id) {
    return { ok: false, 理由: 'BACKUP_FOLDER_ID が設定されていません（控えの保存先が分かりません）' };
  }
  var folder;
  try {
    folder = DriveApp.getFolderById(id);
  } catch (e) {
    return { ok: false, 理由: '控えのフォルダを開けません（消された・権限が無い）: ' + id };
  }

  var 一覧 = [];
  var it = folder.getFiles();
  while (it.hasNext()) {
    var f = it.next();
    var 名 = f.getName();
    var m = /^mayumi-(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})\.dump$/.exec(名);
    if (!m) continue;
    // **ファイル名の日時を使う。**アップロードの時刻ではなく、控えを取った時刻。
    // 送信が遅れても、取った時刻で判断したい。
    一覧.push({
      名: 名,
      大きさ: f.getSize(),
      日時: new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]), Number(m[4]), Number(m[5]))
    });
  }
  一覧.sort(function (a, b) { return b.日時 - a.日時; });
  return { ok: true, 一覧: 一覧, フォルダ名: folder.getName() };
}

function 控え見張り_調べる_() {
  var r = 控え見張り_集める_();
  if (!r.ok) return { 異常: true, 見出し: '控えの保存先が分かりません', 中身: r.理由 };

  if (!r.一覧.length) {
    return { 異常: true, 見出し: '控えが1件もありません', 中身: 'フォルダ「' + r.フォルダ名 + '」は空です。' };
  }

  var 最新 = r.一覧[0];
  var 経過 = (new Date() - 最新.日時) / (1000 * 60 * 60);

  if (経過 > 控え見張り_猶予時間) {
    return {
      異常: true,
      見出し: '控えが ' + Math.floor(経過) + ' 時間 届いていません',
      中身: 'いちばん新しい控え: ' + 最新.名 + '\n件数: ' + r.一覧.length + '件'
    };
  }
  if (最新.大きさ < 控え見張り_小さすぎる) {
    return {
      異常: true,
      見出し: '控えの中身が小さすぎます',
      中身: 最新.名 + ' は ' + Math.round(最新.大きさ / 1024) + 'KB しかありません。取れていない可能性があります。'
    };
  }
  return {
    異常: false,
    見出し: '届いています',
    中身: 'いちばん新しい控え: ' + 最新.名 + '（' + Math.round(最新.大きさ / 1024) + 'KB・' +
      Math.floor(経過) + '時間前）\n件数: ' + r.一覧.length + '件'
  };
}

/** いまの様子を見るだけ。**何も送りません。** */
function 控えが届いているか見る() {
  var r = 控え見張り_調べる_();
  Logger.log('■ ' + (r.異常 ? '**' + r.見出し + '**' : r.見出し));
  Logger.log('');
  String(r.中身).split('\n').forEach(function (行) { Logger.log('  ' + 行); });
  Logger.log('');
  Logger.log('  猶予: ' + 控え見張り_猶予時間 + '時間（3:00に取るので、丸一日空くと24時間）');
  Logger.log('  知らせ先: ' + CONFIG.GMAIL_TO);
  Logger.log('  **何も送っていません。**見張りを仕掛けるには 控えの見張りを始める() を実行してください。');
}

/**
 * 仕掛けから呼ばれる本体。
 * **状態が変わったときだけ送る。**毎日届いたら誰も読まなくなる。
 */
function 控えを見張る() {
  var r = 控え見張り_調べる_();
  var props = PropertiesService.getScriptProperties();
  var 前 = props.getProperty(控え見張り_状態の鍵) || 'ok';
  var いま = r.異常 ? 'ng' : 'ok';

  if (いま === 'ng' && 前 !== 'ng') {
    sendGmail(
      '【控え】まゆみ助産院のバックアップが取れていません',
      r.見出し + '\n\n' + r.中身 + '\n\n' +
      '確かめるところ:\n' +
      '  1. 自宅のPCの電源が入っているか\n' +
      '  2. Docker Desktop が動いているか\n' +
      '  3. タスクスケジューラの「mayumi-db-backup」が有効か\n' +
      '     （前回の結果が 0 なら成功）\n' +
      '  4. server フォルダで .\\scripts\\控えを取る.ps1 を手で流してみる\n\n' +
      '**控えが無いと、壊れたときに会員情報を戻せません。**\n' +
      '直ったら、また自動でお知らせします。'
    );
  } else if (いま === 'ok' && 前 === 'ng') {
    sendGmail(
      '【復旧】まゆみ助産院のバックアップが取れました',
      'また控えが届くようになりました。\n\n' + r.中身
    );
  }
  props.setProperty(控え見張り_状態の鍵, いま);
}

/**
 * 毎朝1回の見張りを仕掛ける。
 * 3:00に取るので、**その数時間あとに見る。**取る前に見ると、
 * 前日ぶんを見て「古い」と鳴ってしまう。
 */
function 控えの見張りを始める() {
  控えの見張りを止める();
  ScriptApp.newTrigger(控え見張り_扱う関数名).timeBased().atHour(8).everyDays(1).create();
  PropertiesService.getScriptProperties().setProperty(控え見張り_状態の鍵, 'ok');
  Logger.log('■ 毎朝8時ごろに、控えが届いているかを見張ります。');
  Logger.log('  猶予: ' + 控え見張り_猶予時間 + '時間');
  Logger.log('  知らせ先: ' + CONFIG.GMAIL_TO);
  Logger.log('  **状態が変わったときだけ送ります。**毎日は届きません。');
}

function 控えの見張りを止める() {
  var 消した = 0;
  ScriptApp.getProjectTriggers().forEach(function (t) {
    if (t.getHandlerFunction() === 控え見張り_扱う関数名) {
      ScriptApp.deleteTrigger(t);
      消した++;
    }
  });
  if (消した) Logger.log('■ 控えの見張りを ' + 消した + ' 件外しました。');
}
