// スプレッドシートと、サーバーへ移した写しがずれていないかを見る道具。
//
//   写しを突き合わせる()   … 各シートの行数を一度に出す
//
// **読むだけ。**元のスプレッドシートは一切変えない。
//
// なぜ要るのか:
//   いまはスプレッドシートが正で、サーバーは写し。自動で同期する仕組みは無い。
//   取り込んだあとにシートを触ると、写しは黙って古くなる。
//   **行を消したり挿したりすると、行番号がずれて取り込みが中身を入れ替える。**
//   まず件数を突き合わせて、動いていないかを確かめる。
//
// 件数が合っていても中身が変わっていることはある。
// 件数が合わなければ、**確実にずれている。**

// シート名と、サーバーに入っている件数（2026-08-17〜18 に取り込んだ時点）。
// サーバー側を数え直したら、ここも直すこと。
var 突合_対象 = [
  { シート: '会員データ',          写し: 153, 備考: '退会を除く' },
  { シート: 'ブログ・お知らせ',      写し: 95 },
  { シート: 'カレンダー',          写し: 143 },
  { シート: 'MENUS',            写し: 13 },
  { シート: '商品マスタ',          写し: 9 },
  { シート: 'カテゴリマスタ',       写し: 7 },
  { シート: 'APP_SUPPORT_FAQ',   写し: 46 },
  { シート: 'PUSH_NOTICES',      写し: 96 },
  { シート: 'MENU_REVENUE',      写し: 112, 備考: '売上177の内訳' },
  { シート: 'PRODUCT_REVENUE',   写し: 65,  備考: '同上' },
  { シート: '管理マスタ',          写し: 22 },
  { シート: 'BACKUP_LOG',        写し: 139 },
  { シート: 'ADMIN_AUDIT_LOG',   写し: 794, 備考: '自動処理を除いた数。全体は9373行' }
];

function 写しを突き合わせる() {
  var ss = getOrCreateSpreadsheet();
  var ずれ = 0;

  Logger.log('■ シートと写しの突き合わせ');
  Logger.log('');
  Logger.log('  シート名                行数    写し    差');
  Logger.log('  ' + Array(46).join('-'));

  突合_対象.forEach(function (x) {
    var sh = ss.getSheetByName(x.シート);
    if (!sh) {
      Logger.log('  ' + x.シート + '  **シートがありません**');
      ずれ += 1;
      return;
    }
    var 行 = Math.max(sh.getLastRow() - 1, 0);

    // 操作履歴だけは、自動処理を除いた数と比べる必要がある。
    // 全体の行数をそのまま比べても意味がないので、ここでは行数だけ出す。
    if (x.シート === 'ADMIN_AUDIT_LOG') {
      Logger.log('  ' + 名前を揃える_(x.シート) + 右寄せ_(行, 7) + 右寄せ_('—', 7) +
        '   （全体の行数。写し794は自動処理を除いた数）');
      Logger.log('     ※ 取り込み時は9373行だった。いまは' + 行 + '行。');
      if (行 !== 9373) {
        Logger.log('     **増えています。新しい操作が' + (行 - 9373) + '件あります。**');
      }
      return;
    }

    var 差 = 行 - x.写し;
    var 印 = 差 === 0 ? '' : '   **ずれています**';
    if (差 !== 0) ずれ += 1;
    Logger.log('  ' + 名前を揃える_(x.シート) + 右寄せ_(行, 7) + 右寄せ_(x.写し, 7) +
      右寄せ_((差 > 0 ? '+' : '') + 差, 6) + 印 +
      (x.備考 ? '   （' + x.備考 + '）' : ''));
  });

  Logger.log('');
  if (ずれ === 0) {
    Logger.log('■ 件数はすべて一致しています。');
    Logger.log('  ただし**件数が合っていても、中身が書き換わっていることはあります。**');
    Logger.log('  行を消したり挿したりしていなければ、写しはほぼそのままです。');
  } else {
    Logger.log('■ **' + ずれ + '件のシートで件数がずれています。**');
    Logger.log('  増えているだけなら、取り込み直せば追いつきます。');
    Logger.log('  **減っている場合は要注意。**行を消すと行番号がずれ、');
    Logger.log('  そのまま取り込むと別の行の中身で上書きされます。');
    Logger.log('  減っていたら、取り込む前にご相談ください。');
  }
  Logger.log('');
  Logger.log('  ※ 読むだけです。シートは変えていません。');
}

function 名前を揃える_(s) {
  var t = String(s);
  while (t.length < 22) t += ' ';
  return t;
}

function 右寄せ_(v, n) {
  var t = String(v);
  while (t.length < n) t = ' ' + t;
  return t;
}
