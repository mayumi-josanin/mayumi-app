#!/bin/sh
# 定時実行。**予約したお知らせ通知を、時間どおりに送るためだけの箱。**
#
# cron（OSの定時実行）を入れないのは、予約システム（mayumi-reserve）・KEM_DDENKI と同じ理由。
# 箱の中に cron を入れると、環境変数（データベースの接続先・通知の鍵）が
# cron の実行環境に引き継がれず、動いているように見えて何も起きない状態になりやすい。
# 素直にループで回して、判定は Django 側のコマンドに任せる。
#
# なぜ要るか（2026-09-20）:
#   予約の「時間が来たら送る」役目は GAS の自動実行だけが担っていて、
#   その GAS が 9/18〜20 の2日間で6回、名前引き（DNS）の失敗で落ちていた。
#   サーバーが自分で送れるようにして、GAS の調子に左右されないようにする。
#
# **表は作らない（migrate しない）。**表を作るのは web の箱だけ。
# 2つの箱が同時に作ろうとすると、途中で止まったときに直しにくい。
set -e

echo "[scheduler] 起動しました"

while true; do
    # 1分おきに見る。予約は分単位で入れるので、これより粗いと約束した時刻から遅れる。
    # 送る予約が無ければ何も書かずにすぐ戻るので、毎分呼んでも負担にならない。
    python manage.py 予約した通知を送る || echo "[scheduler] 予約した通知を送る が失敗しました"
    sleep 60
done
